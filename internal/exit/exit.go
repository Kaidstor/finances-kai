// Package exit — коды выхода finances-kai.
//
// Это контракт с вызывающим: скрипт или агент решает по коду, что делать
// дальше, не разбирая текст. Точная причина — в error.kind конверта --json.
//
// Коды 0–4 значат то же, что у остальных CLI семьи (figma-kai, yk-kai, sec).
package exit

const (
	// OK — сделано.
	OK = 0

	// NotApplied — приложение ответило, но не применило: отвергло сумму или
	// поле, упало внутри (4xx кроме 401/403/404/408, 5xx с JSON-ответом).
	NotApplied = 1

	// Tool — ошибка инструмента, аргументов, настроек или токена: неизвестная
	// команда, неверный флаг, нет профиля, токен отвергнут, нужен --yes,
	// до приложения не достучаться.
	Tool = 2

	// NotFound — нет платежа, тега, контрагента, шаблона, профиля или набора
	// экспорта с таким именем; export за период без платежей.
	NotFound = 3

	// Timeout — приложение не ответило в срок. Повтор безопасен для читающих
	// команд; у создающих сначала проверить через ls, не создался ли платёж.
	Timeout = 4

	// Interrupted — прервано Ctrl+C или SIGTERM.
	Interrupted = 130
)
